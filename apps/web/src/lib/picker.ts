/**
 * 부품 고르기 화면의 크기 상수.
 *
 * `actions.ts`에 둘 수 없다. `'use server'` 파일은 async 함수만 내보낼 수 있어서
 * 상수를 얹으면 빌드가 막힌다. 서버 액션과 클라이언트가 **같은 값**을 봐야
 * "30개씩 보여준다"와 실제로 오는 개수가 어긋나지 않는다.
 */

/** 한 번에 보여주는 개수. 「더 보기」가 이만큼씩 늘린다 */
export const PAGE = 30;

/**
 * 한 번에 끌어갈 수 있는 상한.
 *
 * 클라이언트가 보낸 숫자를 그대로 쓰면 카테고리 전체(최대 4,876건)를 한 번에
 * 끌어갈 수 있다. 화면도 그만큼은 필요하지 않다 — 그쯤 되면 검색어를 더
 * 적는 것이 맞다.
 */
export const MAX_LIMIT = 300;

/**
 * 붙여넣을 수 있는 글자 수.
 *
 * 견적서는 열 줄 남짓이다. 이보다 길면 붙여넣기 사고이거나 우리가 다룰 글이
 * 아니다. 줄 수 제한(`MAX_LINES`)은 이걸 자른 뒤에 걸린다.
 */
export const MAX_QUOTE_CHARS = 4000;

/**
 * 검색어 길이 상한.
 *
 * 서버 액션의 인자는 클라이언트가 만든다. 상한이 없으면 1.5MB짜리 검색어가
 * 조각 20만 개가 되고, 그만큼의 `AND (… like …)`가 붙은 쿼리 두 벌이 동시에
 * 돈다 (실측: 파싱만 100ms). `catch`가 실패를 삼켜 화면에는 흔적도 남지 않는다.
 *
 * 카탈로그에서 가장 긴 이름이 120자 남짓이다. 그보다 긴 검색어는 이름이 아니다.
 */
export const MAX_QUERY_CHARS = 200;
